const GEAR = (() => {
  const n = 8;
  const cx = 12;
  const cy = 12;
  const rOut = 9.6;
  const rIn = 7.4;
  const step = (2 * Math.PI) / n;
  const tipHalf = step * 0.2; // meia largura do dente na ponta
  const baseHalf = step * 0.27; // meia largura do dente na base
  const pt = (r: number, a: number) => `${(cx + r * Math.cos(a)).toFixed(2)} ${(cy + r * Math.sin(a)).toFixed(2)}`;
  let d = "";
  for (let i = 0; i < n; i++) {
    const a = i * step - Math.PI / 2;
    d += `${i === 0 ? "M" : "L"}${pt(rIn, a - baseHalf)} L${pt(rOut, a - tipHalf)} L${pt(rOut, a + tipHalf)} L${pt(rIn, a + baseHalf)} `;
    d += `A${rIn} ${rIn} 0 0 1 ${pt(rIn, a + step - baseHalf)} `;
  }
  return d + "Z";
})();

